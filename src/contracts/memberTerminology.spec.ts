function scannedFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    if (EXCLUDED.some((excluded) => `${path}/`.startsWith(excluded) || path === excluded)) return [];
    if (entry.isDirectory()) return scannedFiles(path);
    return EXTENSIONS.has(extname(entry.name)) ? [path] : [];
  });
}

describe("member terminology", () => {
  const files = ROOTS.flatMap(scannedFiles);
  const found = files.flatMap((file) =>
    readFileSync(file, "utf8")
      .split(/\r?\n/)
      .flatMap((text, index) => findTerminologyViolations(file, index + 1, text)),
  );
  const { violations, stale } = applyAllowList(found, ALLOW_LIST);

  // Without this, a walk that silently finds nothing passes every assertion below.
  it("reads the files in scope", () => {
    expect(files).toContain("src/pages/members/MembersPage.tsx");
    expect(files).toContain(".design-sync/previews/PlatformKpiCard.tsx");
    expect(files.some((file) => file.startsWith("src/api/"))).toBe(false);
    expect(files.length).toBeGreaterThan(500);
  });

  it('names community members "miembro" everywhere', () => {
    expect(violations, `\n${formatViolations(violations)}`).toEqual([]);
  });

  it("keeps no allow-list entry for a line that no longer needs it", () => {
    expect(stale, `\n${formatStaleEntries(stale)}`).toEqual([]);
  });
});
